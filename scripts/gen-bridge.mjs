#!/usr/bin/env node
/**
 * Reads src/lib/locate/bridge.client.js and writes src/lib/locate/bridge.generated.ts
 * with HTML_LOCATE_BRIDGE = JSON.stringify(wrapped script). Escapes </script in the
 * client body so iframe srcDoc injection cannot truncate the script element.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const clientPath = path.join(root, "src/lib/locate/bridge.client.js");
const outPath = path.join(root, "src/lib/locate/bridge.generated.ts");

/**
 * @param {string} clientSource
 * @returns {string} full contents of bridge.generated.ts
 */
export function buildGeneratedFile(clientSource) {
  if (!clientSource.includes("(function")) {
    throw new Error("gen-bridge: bridge.client.js does not look like an IIFE");
  }
  // Escape any </script in the *client body* only — the wrapper close tag must stay
  // as a real </script> so injectLocateBridge can terminate the HTML script element.
  const safeClient = clientSource.replace(/<\/script/gi, "<\\/script");
  const wrapped = `<script data-lh-bridge="1">\n${safeClient}</script>`;
  const banner =
    "/**\n" +
    " * AUTO-GENERATED by scripts/gen-bridge.mjs — do not edit by hand.\n" +
    " * Source: src/lib/locate/bridge.client.js\n" +
    " * Regenerate: npm run gen:bridge\n" +
    " */\n" +
    "\n";
  return `${banner}export const HTML_LOCATE_BRIDGE = ${JSON.stringify(wrapped)};\n`;
}

export function generateBridge(rootDir = root) {
  const client = fs.readFileSync(path.join(rootDir, "src/lib/locate/bridge.client.js"), "utf8");
  const file = buildGeneratedFile(client);
  const dest = path.join(rootDir, "src/lib/locate/bridge.generated.ts");
  fs.writeFileSync(dest, file, "utf8");
  return { dest, bytes: file.length, file };
}

const isMain =
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const { dest, bytes } = generateBridge();
  console.log(`gen-bridge: wrote ${path.relative(root, dest)} (${bytes} bytes)`);
}
